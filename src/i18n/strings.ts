export type StringKey = keyof typeof dictionary;

const languages = ['en', 'fr'] as const;

for (const key of Object.keys(dictionary) as StringKey[]) {
  for (const lang of languages) {
    if (!dictionary[key][lang]) {
      throw new Error(`Missing translation ${lang}.${key}`);
    }
  }
}

export function translate(lang: 'en' | 'fr', key: StringKey): string {
  const value = dictionary[key][lang];
  if (!value) {
    throw new Error(`Missing translation ${lang}.${key}`);
  }
  return value;
}
